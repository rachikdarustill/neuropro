import { NPP_LEGAL } from './legal';

// Ports the two runtime <script> patches from production index.html:
//  1) Cookie policy — заменяет раздел «Сервисы аналитики» и «Аналитические cookie»
//     реальными сведениями о Яндекс Метрике/Вебвизоре (счётчик 110108098).
//  2) Политика ПДн + Согласие — дополняет разделы (формы сайта / поручение обработки /
//     трансграничная передача) сведениями о доставке заявок через Cloudflare + Telegram.
// Applied at build time to a deep clone so the exported LEGAL matches the live site 1:1.

function ymPatch(c) {
  if (!c || !c.sections || c.__ymPatched) return;
  const sec = c.sections.find((s) => /Сервис.*аналит/i.test(s.heading || ''));
  if (!sec) return;
  sec.paras = [
    'На сайте используется сервис веб-аналитики Яндекс Метрика (счётчик № 110108098), предоставляемый ООО «ЯНДЕКС» (Российская Федерация).',
    'Яндекс Метрика собирает обезличенные данные о посещениях: IP-адрес, файлы cookie, сведения об устройстве и браузере, источник перехода, просматриваемые страницы и действия пользователя на сайте. На сайте включён инструмент «Вебвизор», который записывает действия пользователя на страницах (перемещения курсора, клики, прокрутку, заполнение полей форм без передачи их содержимого) для анализа удобства использования сайта.',
    'Собранные данные обрабатываются на стороне ООО «ЯНДЕКС» в соответствии с Условиями использования сервиса Яндекс Метрика (yandex.ru/legal/metrica_termsofuse) и Политикой конфиденциальности Яндекса (yandex.ru/legal/confidential).',
    'Яндекс Метрика подключается только после согласия пользователя на аналитические cookie (баннер cookie на сайте). При отказе или отсутствии согласия данные Яндекс Метрикой не собираются. Отозвать ранее данное согласие можно, очистив файлы cookie и данные сайта в браузере. Отключение аналитических cookie не влияет на доступ к основным функциям сайта.',
  ];
  const sec8 = c.sections.find((s) => /Аналитические cookie/i.test(s.heading || ''));
  if (sec8) sec8.paras = ['Оценка посещаемости и эффективности страниц сайта. Используется Яндекс Метрика (счётчик № 110108098, включая «Вебвизор»); собираемые данные передаются ООО «ЯНДЕКС».'];
  c.__ymPatched = true;
}

function addPara(sec, marker, text) {
  if (!sec || !Array.isArray(sec.paras)) return;
  if (sec.paras.some((p) => p && p.indexOf(marker) > -1)) return;
  sec.paras.push(text);
}
function find(d, re) {
  return d && d.sections ? d.sections.find((s) => re.test(s.heading || '')) : null;
}
function tgPatch(pol, con) {
  if (!pol || !pol.sections || pol.__tgPatched) return;
  addPara(find(pol, /формы сайта/i), 'Telegram',
    'Данные, отправленные через форму обратной связи (имя, название компании, контактный телефон, адрес электронной почты), передаются Оператору для обработки обращения. Техническая доставка обращения осуществляется через сервис Cloudflare Workers (Cloudflare, Inc.) и мессенджер Telegram: уведомление о новой заявке поступает в рабочий чат Оператора в Telegram. Передаются только сведения, которые пользователь добровольно указал в форме.');
  addPara(find(pol, /Поручение обработки.*третьим/i), 'Telegram',
    'При приёме обращений с сайта в передаче и обработке данных участвуют: Cloudflare, Inc. (маршрутизация и передача запросов формы) и Telegram (Telegram FZ-LLC / Telegram Messenger Inc.) — доставка уведомлений о заявках в рабочий чат Оператора. Обработка указанными лицами осуществляется в объёме, необходимом для передачи обращения.');
  addPara(find(pol, /Трансгранич/i), 'Telegram',
    'Поскольку доставка обращений с сайта осуществляется через мессенджер Telegram и сервис Cloudflare, серверы которых расположены за пределами Российской Федерации, обработка указанных в форме данных связана с трансграничной передачей. Оператор осуществляет её при наличии правовых оснований (согласие субъекта и (или) исполнение договора) с учётом статьи 12 Федерального закона № 152-ФЗ и до начала трансграничной передачи уведомляет Роскомнадзор.');
  if (con && con.sections) {
    addPara(find(con, /Поручение обработки третьим/i), 'Telegram',
      'Субъект уведомлён и согласен, что переданные через форму данные доставляются Оператору с использованием сервиса Cloudflare и мессенджера Telegram, в том числе посредством трансграничной передачи за пределы Российской Федерации.');
  }
  pol.__tgPatched = true;
}

const LEGAL = structuredClone(NPP_LEGAL);
ymPatch(LEGAL.cookie);
tgPatch(LEGAL.policy, LEGAL.consent);

export { LEGAL };
